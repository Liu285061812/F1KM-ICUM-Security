#include "device.h"
#include "icum_ostm.h"

__IOREG(ICUM_OSTM0CMP, 0xFFFEE000, __READ_WRITE, uint32);
__IOREG(ICUM_OSTM0TS, 0xFFFEE014, __READ_WRITE, uint8);
__IOREG(ICUM_OSTM0TT, 0xFFFEE018, __READ_WRITE, uint8);
__IOREG(ICUM_OSTM0CTL, 0xFFFEE020, __READ_WRITE, uint8);
__IOREG(ICUM_CTLREGICUM_GPIO, 0xFFFEE208, __READ_WRITE, uint32);
__IOREG(ICUM_ICICUOSTM0, 0xFFFEEA0E, __READ_WRITE, uint16);

/* CPUCLK is 240 MHz; CKDIVMD=1 makes CPUCLK_L (the OSTM clock) CPUCLK/4. */
#define ICUM_OSTM0_CLOCK_HZ       60000000UL
#define ICUM_OSTM0_INTERVAL_MS    100UL
#define ICUM_OSTM0_COMPARE_VALUE \
    ((ICUM_OSTM0_CLOCK_HZ / 1000UL) * ICUM_OSTM0_INTERVAL_MS - 1UL)

#define ICUM_GPIO_SECOUT0_MASK    0x00000007UL
#define ICUM_GPIO_SECOUT0_ENABLE  0x00000006UL

void icum_ostm_init(void)
{
    ICUM_OSTM0TT = 1u;
    ICUM_OSTM0CTL = 0u;
    ICUM_OSTM0CMP = ICUM_OSTM0_COMPARE_VALUE;

    /* OPBT12.ICUMOPGPIO must be set to 1 to enable ICUM GPIO control. */
    ICUM_CTLREGICUM_GPIO =
        (ICUM_CTLREGICUM_GPIO & ~ICUM_GPIO_SECOUT0_MASK) |
        ICUM_GPIO_SECOUT0_ENABLE;

    ICUM_ICICUOSTM0 = 0x0040u;
    ICUM_OSTM0TS = 1u;
    __EI();
}

#pragma ghs interrupt
void INTICUOSTM0(void)
{
    ICUM_CTLREGICUM_GPIO ^= 0x00000001u;
}
