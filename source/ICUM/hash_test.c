#include "hash_test.h"

static int hash_matches(icum_hash_algorithm algorithm,
                        const char *message,
                        unsigned long message_length,
                        const unsigned char *expected)
{
    unsigned char digest[64];
    unsigned long i, size;

    size=icum_hash_digest_size(algorithm);
    if (!icum_hash_compute(algorithm,(const unsigned char *)message,message_length,digest)) 
        return 0;
    for(i=0ul;i<size;++i) 
    {
        if(digest[i]!=expected[i]) 
            return 0;
    }
    return 1;
}

